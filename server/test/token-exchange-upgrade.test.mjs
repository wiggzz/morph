import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {PluginManager} from '../src/plugins.mjs';
import {PluginPackages} from '../src/plugin-packages.mjs';
import {PluginInstances} from '../src/plugin-instances.mjs';
import {primitiveDocs,validateAuth} from '../src/plugin-auth.mjs';

test('an existing token-only Garmin workspace needs explicit publication; upgraded recipe preserves methods and old accounts',async t=>{
  const directory=new URL('../../plugins/',import.meta.url).pathname;
  const dataDir=fs.mkdtempSync(path.join(os.tmpdir(),'morph-upgrade-'));
  const empty=path.join(dataDir,'empty');fs.mkdirSync(empty);
  t.after(()=>fs.rmSync(dataDir,{recursive:true,force:true}));
  const bundled=JSON.parse(fs.readFileSync(path.join(directory,'garmin-personal','manifest.json')));
  const id=bundled.id;
  const legacy={...bundled,auth:{type:'bearer'},driver:'rest-json',methods:{listActivities:{description:'Activities',input:{properties:{}},request:{method:'GET',path:'/activities'}}}};
  const seed=new PluginPackages({directory:empty,dataDir});
  seed.create(id,{'/manifest.json':JSON.stringify(legacy),'/index.ts':"import {plugins} from '@morph/plugins'; export const listActivities = (id,args={}) => plugins.call(id,'listActivities',args);"});
  seed.publish(id,seed.validate(id).id);
  const requests=[];
  const token='header.'+Buffer.from(JSON.stringify({exp:Math.floor(Date.now()/1000)+3600})).toString('base64url')+'.signature';
  const plugins=new PluginManager({directory,dataDir,trusted:true,transport:async(url,options)=>{requests.push({url,...options});return url===bundled.auth.exchange.url?token:{echo:options.headers.Authorization};}});
  const instances=new PluginInstances({dataDir,plugins});t.after(()=>{instances.close();plugins.close();});
  assert.equal(plugins.get(id).auth.type,'bearer','startup must not overwrite a user workspace with bundled source');
  const docs=plugins.docs(id);
  assert.equal(docs.auth.type,'bearer','tool docs honestly describe the installed release');
  assert.equal(docs.bundledExample.auth.type,'token-exchange','tool docs expose the new shipped example despite the collision');
  validateAuth(docs.bundledExample.auth);
  validateAuth(docs.primitives.credentials.find(x=>x.type==='token-exchange').example);
  assert.equal(plugins.packages.get(id).releases.index.active,1,'reading shipped examples must not publish or replace project source');
  const old=instances.open(id,{slot:'personal'},'activity-app');instances.configure(old.id,{key:'OLD-PRIVATE-ACCESS'});
  const upgraded={...legacy,version:'0.2.0',auth:bundled.auth};
  plugins.packages.write(id,'/manifest.json',JSON.stringify(upgraded));
  const release=plugins.packages.publish(id,plugins.packages.validate(id).id,'Protected key exchange');plugins.reload();
  assert.equal(release.version,2);assert.equal(plugins.docs(id).auth.type,'token-exchange');
  assert.ok(plugins.docs(id).methods.listActivities,'existing app method contract survives');
  assert.equal(instances.open(id,{slot:'personal'},'activity-app').id,old.id,'old slots remain pinned');
  assert.equal(instances.metadata(old.id).auth.type,'bearer');
  const fresh=instances.open(id,{slot:'personal-api-key'},'activity-app');
  assert.equal(instances.metadata(fresh.id).auth.type,'token-exchange');assert.equal(fresh.connected,false);
  assert.equal(instances.metadata(fresh.id).configured,false,'no credential transfer across recipes');
  instances.configure(fresh.id,{key:'NEW-PRIVATE-KEY'});await instances.exchange(fresh.id);
  await instances.call(fresh.id,'listActivities',{}, {surface:'agent'});
  assert.equal(requests[1].headers.Authorization,'Bearer '+token);
  assert.equal(instances.metadata(old.id).connected,true);
  const example=primitiveDocs.credentials.find(x=>x.type==='token-exchange').example;
  validateAuth(example);assert.equal(example.exchange.response.format,'text','builder docs expose the exact valid schema');
});
